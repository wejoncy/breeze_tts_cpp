#!/usr/bin/env python3
"""Small paired BF16/FP8 speech regression set, with optional local Whisper scoring.
The ASR environment is a validation dependency, not an engine dependency.
"""

import argparse
import hashlib
import json
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
ZH = "你好，欢迎使用语音合成。这段声音由原生引擎生成，支持批量处理和实时流式输出。"
EN = "Hello and welcome. This speech is generated by a native C plus plus engine, with each audio frame delivered as soon as it is ready."
CASES = [
    ("zh", "zh", ZH, None),
    ("en", "en", EN, None),
    (
        "zh_short",
        "zh",
        "今天天气很好，我们一起去公园散步，听听风吹过树叶的声音。",
        None,
    ),
    (
        "en_short",
        "en",
        "The meeting starts at nine tomorrow morning. Please bring your notes and arrive on time.",
        None,
    ),
    (
        "zh_reference",
        "zh",
        "今天的测试包括参考音频、批量处理和连续的语音输出。",
        ("chinese.wav", ZH),
    ),
    (
        "en_reference",
        "en",
        "Thank you for listening. We hope you have a wonderful day.",
        ("english.wav", EN),
    ),
]


def distance(a, b):
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        row = [i]
        for j, cb in enumerate(b, 1):
            row.append(min(row[-1] + 1, prev[j] + 1, prev[j - 1] + (ca != cb)))
        prev = row
    return prev[-1]


def normalized(text, language):
    text = text.lower().replace("c++", "c plus plus")
    if language == "zh":
        return [c for c in text if c.isalnum()]
    return "".join(c if c.isalnum() or c.isspace() else " " for c in text).split()


def generate(args):
    from tts_cpp import Engine

    if args.manifest:
        cases = json.loads(args.manifest.read_text())["cases"]
    else:
        cases = [
            {
                "case": name,
                "language": lang,
                "expected": text,
                "reference": {
                    "wav": str(ROOT / "artifacts/final" / ref[0]),
                    "text": ref[1],
                }
                if ref
                else None,
            }
            for name, lang, text, ref in CASES
        ]
    options = {"max_frames": args.max_frames, "temperature": 0.9}
    run = {
        "seeds": args.seeds,
        "options": options,
        "batch": 1,
        "model": str(args.model.resolve()),
        "library_sha256": hashlib.sha256(
            (ROOT / "build/libtts.so").read_bytes()
        ).hexdigest(),
        "manifest_sha256": hashlib.sha256(args.manifest.read_bytes()).hexdigest()
        if args.manifest
        else None,
    }
    (args.output / "run.json").write_text(json.dumps(run, indent=2) + "\n")
    records = []
    for precision in ("bf16", args.quantization):
        with Engine(
            model=args.model,
            quantization=None if precision == "bf16" else precision,
            max_batch=1,
        ) as engine:
            engine.run_async()
            for case in cases:
                name, ref = case["case"], case.get("reference")
                request = {"text": case["expected"]}
                reference = None
                if ref:
                    reference = engine.prepare_reference(ref["wav"], ref["text"])
                    request["reference"] = reference
                try:
                    for seed in args.seeds:
                        pcm, stats = engine.generate(
                            [request], dict(options, seed=seed)
                        )
                        suffix = f"-s{seed}" if len(args.seeds) > 1 else ""
                        path = args.output / f"{precision}-{name}{suffix}.wav"
                        with wave.open(str(path), "wb") as f:
                            f.setparams((1, 2, 24000, 0, "NONE", "not compressed"))
                            f.writeframes(pcm[0])
                        record = dict(
                            case,
                            precision=precision,
                            seed=seed,
                            wav=str(path.resolve()),
                            stats=stats,
                        )
                        records.append(record)
                        (args.output / "speech.json").write_text(
                            json.dumps(records, ensure_ascii=False, indent=2) + "\n"
                        )
                        print(json.dumps(record, ensure_ascii=False), flush=True)
                finally:
                    if reference:
                        reference.close()


def score(args):
    import numpy as np
    import soundfile as sf
    import torch
    from scipy.signal import resample_poly
    from transformers import AutoModelForSpeechSeq2Seq, AutoProcessor

    torch.set_num_threads(4)
    model_id = "openai/whisper-large-v3-turbo"
    processor = AutoProcessor.from_pretrained(model_id, local_files_only=True)
    model = (
        AutoModelForSpeechSeq2Seq.from_pretrained(
            model_id, local_files_only=True, dtype=torch.float16
        )
        .cuda()
        .eval()
    )
    records = json.loads((args.output / "speech.json").read_text())
    for r in records:
        audio, sr = sf.read(r["wav"], dtype="float32")
        assert sr == 24000
        features = processor(
            resample_poly(audio, 2, 3),
            sampling_rate=16000,
            return_tensors="pt",
            return_attention_mask=True,
        )
        with torch.inference_mode():
            tokens = model.generate(
                input_features=features.input_features.cuda().half(),
                attention_mask=features.attention_mask.cuda(),
                language=r["language"],
                task="transcribe",
                max_new_tokens=256,
                do_sample=False,
            )
        transcription = processor.batch_decode(tokens, skip_special_tokens=True)[
            0
        ].strip()
        ref = normalized(r["expected"], r["language"])
        hyp = normalized(transcription, r["language"])
        r.update(
            transcription=transcription,
            errors=distance(ref, hyp),
            units=len(ref),
            error_rate=distance(ref, hyp) / len(ref),
            peak=float(np.abs(audio).max()),
            rms=float(np.sqrt(np.mean(audio**2))),
            clipping_fraction=float(np.mean(np.abs(audio) >= 0.999)),
        )
        print(json.dumps(r, ensure_ascii=False), flush=True)
    summary = {}
    for precision in ("bf16", args.quantization):
        for language in ("zh", "en"):
            group = [
                r
                for r in records
                if r["precision"] == precision and r["language"] == language
            ]
            errors = sum(r["errors"] for r in group)
            units = sum(r["units"] for r in group)
            summary[f"{precision}_{language}"] = {
                "errors": errors,
                "units": units,
                "error_rate": errors / units,
                "metric": "CER" if language == "zh" else "WER",
                "samples": len(group),
            }
    result = {
        "summary": summary,
        "records": records,
        "limitation": "Six paired utterances; ASR consistency is not a perceptual quality or speaker-similarity test.",
    }
    (args.output / "asr.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    )
    print(json.dumps(summary, indent=2), flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=ROOT / "models/Breeze-TTS-2")
    parser.add_argument("--output", type=Path, default=ROOT / "artifacts/fp8/quality")
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--seeds", type=int, nargs="+", default=[42])
    parser.add_argument("--max-frames", type=int, default=256)
    parser.add_argument("--quantization", choices=("fp8", "int8"), default="fp8")
    parser.add_argument("--stage", choices=("generate", "score"), required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    (generate if args.stage == "generate" else score)(args)
