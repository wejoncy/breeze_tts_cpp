#!/usr/bin/env python3
"""Fixed-frame native benchmarks using the TVM FFI Python bridge."""

import argparse
import json
import statistics
import sys
import time
from itertools import pairwise
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "python"))
from tts_cpp import Engine
from request_schema import validate

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--model", type=Path, required=True)
parser.add_argument("--library", type=Path)
parser.add_argument("--batches", default="1,2,4,8")
parser.add_argument("--frames", type=int, default=24)
parser.add_argument("--repeats", type=int, default=4)
parser.add_argument("--cfg", type=float, default=1)
parser.add_argument("--no-graph", action="store_true")
parser.add_argument("--ref-audio", type=Path)
parser.add_argument("--ref-text")
parser.add_argument("--dual-cfg", action="store_true")
parser.add_argument("--output", type=Path, default=Path("benchmark.json"))
parser.add_argument("--quantization", choices=("fp8", "int8"))
args = parser.parse_args()
batches = [int(b) for b in args.batches.split(",")]
if args.repeats < 2:
    parser.error("use at least two iterations to separate cold and warm")
engine = Engine(
    args.library,
    args.model,
    max_batch=max(batches),
    quantization=args.quantization,
)
engine.run_async()
texts = [
    "你好，欢迎使用语音合成。这是一段原生引擎生成的测试语音，我们正在检查连续输出是否清晰流畅。",
    "Hello and welcome. This speech is generated by a native C plus plus engine, with each audio frame delivered as soon as it is ready.",
]
reference = None
encode_ms = None
if args.ref_audio:
    start = time.perf_counter()
    reference = engine.prepare_reference(
        args.ref_audio,
        args.ref_text
        or "你好，欢迎使用语音合成。这段声音由原生引擎生成，支持批量处理和实时流式输出。",
    )
    encode_ms = (time.perf_counter() - start) * 1000
    print(
        json.dumps(
            dict(reference_frames=reference.frames, reference_prepare_ms=encode_ms)
        ),
        flush=True,
    )
results = []
try:
    for batch in batches:
        observations = []
        for iteration in range(args.repeats):
            payload = {
                "requests": [
                    {
                        "text": texts[i % 2],
                        "instruction": "A calm, clear and natural voice."
                        if args.cfg != 1 or args.dual_cfg
                        else "",
                    }
                    for i in range(batch)
                ],
                "max_frames": args.frames,
                "cfg_scale": args.cfg,
                "use_cuda_graph": 0 if args.no_graph else 1,
            }
            if reference:
                for r in payload["requests"]:
                    r["reference"] = reference
            if args.dual_cfg:
                payload.update(cfg_scale_ref=2.0, cfg_scale_ins=3.0)
            requests, options = validate(payload, True, engine.default_options())
            timestamps = []

            def receive(index, pcm, timestamps=timestamps):
                if index == 0:
                    timestamps.append(time.perf_counter())

            stats = engine.generate(requests, options, receive)
            stats["iteration"] = iteration
            intervals = [(b - a) * 1000 for a, b in pairwise(timestamps[2:])]
            stats["steady_frame_ms"] = (
                statistics.median(intervals) if intervals else None
            )
            stats["rtf"] = (
                stats["total_ms"] / 1000 / stats["audio_seconds"]
                if stats["audio_seconds"]
                else None
            )
            stats["audio_seconds_per_second"] = stats["audio_seconds"] / (
                stats["total_ms"] / 1000
            )
            observations.append(stats)
            print(json.dumps(dict(batch=batch, **stats)), flush=True)
        summary = {
            k: statistics.median(o[k] for o in observations[1:])
            for k in (
                "first_audio_ms",
                "total_ms",
                "rtf",
                "steady_frame_ms",
                "audio_seconds_per_second",
            )
        }
        results.append(
            {
                "batch": batch,
                "quantization": engine.quantization,
                "cfg_scale": args.cfg,
                "dual_cfg": args.dual_cfg,
                "reference_prepare_ms": encode_ms,
                "cuda_graph": not args.no_graph,
                "warm_median": summary,
                "observations": observations,
            }
        )
finally:
    if reference:
        reference.close()
    engine.close()
args.output.write_text(json.dumps(results, indent=2) + "\n")
